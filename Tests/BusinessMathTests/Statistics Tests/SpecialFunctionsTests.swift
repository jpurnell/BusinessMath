//  The shared special-function layer under Gamma, Erlang, Chi-squared, Beta, F,
//  Pearson V, Pearson VI and the Johnson family.
//
//  Reference: scipy 1.17.1 via Scripts/reference-fixtures/generate.py. The exact
//  version is asserted below, because a parameterisation or naming change between
//  SciPy releases invalidates a fixture silently.
