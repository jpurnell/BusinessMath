	fixtures.append(Fixture(name: "random\(seed)", edges: edges, isolated: isolated))
}

func literal(_ edges: [Edge]) -> String {
	edges.map { "(\"\($0.0)\", \"\($0.1)\", \($0.2))" }.joined(separator: ", ")
}

